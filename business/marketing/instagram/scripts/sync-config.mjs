// npm run sync: checks config.ts prices against business/playbook.md §2–3, then writes
// brand/generated.js (what the compositions read) and brand/river.svg. The river drawing
// and the bridge logo come straight from the website, so the two never drift apart.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { config } from '../config.ts';

const kit = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const repo = (p) => kit(`../../../${p}`);
const fail = (msg) => {
  console.error(`sync: ${msg}`);
  process.exit(1);
};

// 1. Prices: the playbook wins.
const playbook = readFileSync(repo('business/playbook.md'), 'utf8').split('\n');
const row = (label) => {
  const line = playbook.find((l) => l.startsWith(`| ${label} |`));
  if (!line) fail(`couldn't find the "${label}" row in business/playbook.md`);
  return line.split('|').slice(2, -1).map((cell) => (cell.match(/\$[\d,]+/g) || []).map((n) => Number(n.replace(/[^0-9]/g, ''))));
};
const pagesLine = playbook.find((l) => l.startsWith('| Pages |'));
if (!pagesLine) fail('couldn\'t find the "Pages" row in business/playbook.md');
const pageCounts = pagesLine.split('|').slice(2, -1).map((cell) => Number(cell.match(/Up to (\d+)/)?.[1]) || null);
const careLine = playbook.find((l) => l.startsWith('One care plan at '));
if (!careLine) fail('couldn\'t find the "One care plan at" line in business/playbook.md §3');
const carePrice = Number(careLine.match(/^One care plan at \$(\d+)/)?.[1]);
const hourlyLine = playbook.find((l) => l.includes('billed at $') && l.includes('/hr in 30-minute blocks'));
if (!hourlyLine) fail('couldn\'t find the hourly rate line in business/playbook.md §3');
const hourlyRate = Number(hourlyLine.match(/billed at \$(\d+)\/hr/)?.[1]);
const checks = [
  ['§2 Dallas price', row('Dallas price'), config.packages.map((p) => [p.priceFrom])],
  ['§2 pages', pageCounts, config.packages.map((p) => p.pages)],
  ['§3 care plan price', carePrice, config.care.monthly],
  ['§3 hourly rate', hourlyRate, config.hourlyRate],
];
for (const [what, playbookValues, configValues] of checks) {
  if (JSON.stringify(playbookValues) !== JSON.stringify(configValues)) {
    fail(`${what} in config.ts is ${JSON.stringify(configValues)}, playbook says ${JSON.stringify(playbookValues)}. Fix config.ts.`);
  }
}

// 2. The river drawing, from the site's hero.
const hero = readFileSync(repo('site/src/components/site/RiverHero.astro'), 'utf8');
const riverPath = hero.match(/const path =\s*'([^']+)'/)?.[1];
const viewBox = hero.match(/class="river-svg" viewBox="([^"]+)"/)?.[1];
const stops = [...hero.matchAll(/\{ name: '([^']+)', x: (\d+), y: (\d+), labelY: (\d+)(, hideOnPhone: true)? \}/g)].map(
  (m) => ({ name: m[1], x: +m[2], y: +m[3], labelY: +m[4], phone: !m[5] }),
);
if (!riverPath || !viewBox || stops.length < 2) fail('couldn\'t read the river path and stops from RiverHero.astro');

// 3. The bridge logo, from the site. Each subpath becomes its own stroke so it can draw in order.
copyFileSync(repo('site/public/logo-mark.svg'), kit('brand/logo-mark.svg'));
const logoSvg = readFileSync(kit('brand/logo-mark.svg'), 'utf8');
const logoParts = [...logoSvg.matchAll(/<path d="([^"]+)" stroke-width="([\d.]+)"/g)].flatMap(([, d, width]) =>
  d.split(/(?=M)/).map((sub) => sub.trim()).map((sub) => ({
    d: sub,
    width: +width,
    role: sub.includes('Q') ? 'arch' : sub.includes('H') ? 'deck' : 'cable',
  })),
);
if (!logoParts.some((p) => p.role === 'deck') || !logoParts.some((p) => p.role === 'arch')) fail('couldn\'t read the logo paths');

const data = { config, river: { path: riverPath, viewBox, stops }, logo: { viewBox: '0 0 48 32', parts: logoParts } };
writeFileSync(
  kit('brand/generated.js'),
  `// Generated by \`npm run sync\` from config.ts, the site's RiverHero.astro and logo-mark.svg. Don't edit.\nwindow.TWC_DATA = ${JSON.stringify(data, null, 2)};\n`,
);

// 4. A standalone river.svg that draws itself in when opened anywhere (browser, slides, design tools).
// Labels use Archivo, embedded so the file looks right outside the kit.
const font = readFileSync(kit('brand/fonts/archivo-latin-wdth-normal.woff2')).toString('base64');
const [, , vbW] = viewBox.split(' ').map(Number);
const stopMarkup = stops
  .map(
    (s, i) =>
      `  <g class="stop" style="animation-delay:${(0.55 + i * 0.3).toFixed(2)}s"><circle cx="${s.x}" cy="${s.y}" r="8"/><text x="${s.x}" y="${s.labelY}">${s.name}</text></g>`,
  )
  .join('\n');
writeFileSync(
  kit('brand/river.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${vbW}" overflow="visible">
  <title>The Trinity River with Dallas neighborhoods along it</title>
  <!-- Generated by \`npm run sync\` from the site's RiverHero.astro. Don't edit. -->
  <style>
    @font-face { font-family: "Archivo Variable"; src: url(data:font/woff2;base64,${font}) format("woff2"); font-weight: 100 900; font-stretch: 62% 125%; }
    .bank { fill: none; stroke: #1D6B66; stroke-width: 30; stroke-linecap: round; opacity: 0.12; }
    .line { fill: none; stroke: #1D6B66; stroke-width: 4; stroke-linecap: round; stroke-dasharray: 1; stroke-dashoffset: 0; }
    .stop circle { fill: #FAFBF8; stroke: #13262B; stroke-width: 2.5; }
    .stop text { fill: #13262B; font-family: "Archivo Variable", system-ui, sans-serif; font-size: 19px; font-weight: 650; font-stretch: 110%; text-anchor: middle; }
    @media (prefers-reduced-motion: no-preference) {
      .line { stroke-dashoffset: 1; animation: draw 2.2s cubic-bezier(0.45, 0.05, 0.25, 1) 0.2s forwards; }
      .stop { opacity: 0; animation: stop-in 0.45s ease-out forwards; }
    }
    @keyframes draw { to { stroke-dashoffset: 0; } }
    @keyframes stop-in { from { opacity: 0; transform: translateY(6px); } to { opacity: 1; transform: none; } }
  </style>
  <path class="bank" d="${riverPath}"/>
  <path class="line" pathLength="1" d="${riverPath}"/>
${stopMarkup}
</svg>
`,
);

console.log(`sync: prices match the playbook; wrote brand/generated.js and brand/river.svg (${stops.length} stops, ${logoParts.length} logo strokes)`);
